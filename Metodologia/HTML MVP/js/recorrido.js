function currentSchedule() {
    return scheduleSets[lineSelect.value]?.[daySelect.value]?.[routeSelect.value];
}

function selectedLineLabel() {
    return lineSelect.selectedOptions[0]?.textContent || `Línea ${lineSelect.value}`;
}

function selectedCompanyName() {
    return lineSelect.selectedOptions[0]?.dataset.company === "BUTINI"
        ? "A. Buttini"
        : "Autotransportes Iselín S.A.";
}

function getTripDeparture(trip) {
    return trip.find(Boolean) || "Horario no informado";
}

function populateRoutesForDay() {
    const schedules = scheduleSets[lineSelect.value]?.[daySelect.value];
    routeSelect.replaceChildren();

    const placeholder = document.createElement("option");
    placeholder.value = "";
    placeholder.textContent = schedules
        ? "Seleccioná un recorrido para ver sus horarios"
        : "No hay recorridos cargados para este día";
    placeholder.disabled = true;
    placeholder.selected = true;
    routeSelect.append(placeholder);

    if (!schedules || Object.keys(schedules).length === 0) {
        routeField.hidden = true;
        routeSelect.disabled = true;
        routeControls.classList.remove("has-route");
        scheduleCard.hidden = !daySelect.value;
        if (daySelect.value) {
            populateDepartures(null);
            document.querySelector("#schedule-title").textContent = "Servicio no disponible";
            document.querySelector(".schedule-kicker").textContent =
                `${selectedLineLabel()} · ${daySelect.selectedOptions[0]?.textContent.toUpperCase() || ""}`;
            document.querySelector("#schedule-notice").textContent =
                "No se informan frecuencias para esta línea en el día seleccionado.";
        }
        if (routeMapLayers) routeMapLayers.clearLayers();
        return;
    }

    const scheduleList = Object.values(schedules);
    scheduleList.forEach((schedule) => {
        const option = document.createElement("option");
        option.value = schedule.code;
        option.textContent = `${schedule.code} · ${schedule.title || "Izuel - Doña Paula - Cuadro Nacional x Salas"}`;
        routeSelect.append(option);
    });

    routeField.hidden = false;
    routeSelect.disabled = false;
    routeControls.classList.add("has-route");

    // Selecciona por defecto el primer recorrido disponible pero mantiene el cuadro oculto hasta presionar Aceptar
    if (scheduleList.length > 0) {
        routeSelect.selectedIndex = 1;
    }
    scheduleCard.hidden = true;
    if (routeMapLayers) routeMapLayers.clearLayers();
}

function populateDepartures(schedule) {
    departureSelect.replaceChildren();
    const badge = document.querySelector("#schedule-badge");
    const scheduleDetails = document.querySelector("#schedule-details");
    const noFrequencies = document.querySelector("#no-frequencies");

    if (!schedule) {
        const routeTitle = (routeSelect.selectedOptions[0]?.textContent || "")
            .replace(/^\S+\s·\s/, "")
            .replace(/\s\(solo sábados\)$/, "");
        document.querySelector("#schedule-title").textContent = routeTitle || "Recorrido no disponible";
        document.querySelector(".schedule-kicker").textContent =
            `${routeSelect.value || ""} · ${daySelect.selectedOptions[0]?.textContent.toUpperCase() || ""}`;
        document.querySelector("#departure-count").textContent = "—";
        document.querySelector("#first-departure").textContent = "—";
        document.querySelector("#last-departure").textContent = "—";
        document.querySelector("#stop-count").textContent = "0 paradas";
        document.querySelector("#selected-trip-label").textContent = "";
        document.querySelector("#schedule-notice").textContent = "";
        timeline.replaceChildren();
        departureSelect.disabled = true;
        scheduleDetails.hidden = true;
        noFrequencies.hidden = false;
        badge.replaceChildren(document.createElement("span"), " Sin frecuencias");
        badge.classList.add("is-unavailable");
        if (routeMapLayers) routeMapLayers.clearLayers();
        return;
    }

    departureSelect.disabled = false;
    scheduleDetails.hidden = false;
    noFrequencies.hidden = true;
    badge.replaceChildren(document.createElement("span"), " Cuadro recibido");
    badge.classList.remove("is-unavailable");

    schedule.trips.forEach((trip, index) => {
        const option = document.createElement("option");
        option.value = String(index);
        option.textContent = `Salida ${getTripDeparture(trip)}`;
        departureSelect.append(option);
    });

    document.querySelector("#schedule-title").textContent =
        schedule.title || "Izuel - Doña Paula - Cuadro Nacional x Salas";
    document.querySelector(".schedule-kicker").textContent =
        `${schedule.code} · ${schedule.days.toUpperCase()}`;
    document.querySelector("#line-badge").textContent = selectedLineLabel();
    document.querySelector("#schedule-notice").textContent = {
        lv: "Estos son los horarios de lunes a viernes. Los cuadros de sábados, domingos y feriados se consultan por separado.",
        s: "Estos son los horarios del sábado. Los cuadros de domingos y feriados se consultan por separado.",
        d: "Estos son los horarios recibidos para domingos y feriados. Solo aparecen los recorridos con cuadro cargado."
    }[daySelect.value];
    document.querySelector("#departure-count").textContent = String(schedule.trips.length);
    document.querySelector("#first-departure").textContent = getTripDeparture(schedule.trips[0]);
    document.querySelector("#last-departure").textContent = getTripDeparture(schedule.trips.at(-1));
    document.querySelector("#stop-count").textContent = `${schedule.stops.length} paradas`;

    renderSelectedTrip();
    renderRouteMap(schedule);
}

function renderSelectedTrip() {
    const schedule = currentSchedule();
    const tripIndex = Number(departureSelect.value) || 0;
    const trip = schedule?.trips[tripIndex];
    if (!schedule || !trip || trip.length !== schedule.stops.length) {
        return;
    }

    timeline.replaceChildren();
    schedule.stops.forEach((stop, index) => {
        const item = document.createElement("li");
        item.className = "timeline-item";
        item.dataset.stopIndex = String(index);

        const time = document.createElement("time");
        time.className = "timeline-time";
        if (trip[index]) time.dateTime = trip[index];
        time.textContent = trip[index] || "—";

        const content = document.createElement("div");
        content.className = "timeline-content";
        const stopNumber = document.createElement("span");
        stopNumber.className = "timeline-index";
        stopNumber.textContent = String(index + 1).padStart(2, "0");
        const name = document.createElement("h4");
        name.textContent = stop;

        content.append(stopNumber, name);
        item.append(time, content);

        // Click en la parada para centrarla en el mapa y abrir su popup
        item.addEventListener("click", () => {
            highlightTimelineItem(index);
            if (stopMarkers[index] && routeMap) {
                const marker = stopMarkers[index];
                routeMap.setView(marker.getLatLng(), 15, { animate: true });
                marker.openPopup();
            }
        });

        timeline.append(item);
    });

    const firstTimedStopIndex = trip.findIndex(Boolean);
    document.querySelector("#selected-trip-label").textContent =
        `Paradas en orden para la salida de las ${getTripDeparture(trip)} desde ${schedule.stops[firstTimedStopIndex]}. (Clic para ubicar en mapa)`;

    // Actualizar popups de los marcadores con los nuevos horarios
    if (stopMarkers.length === schedule.stops.length) {
        stopMarkers.forEach((marker, i) => {
            const timeLabel = trip[i] ? `${trip[i]} hs` : "No asignado";
            marker.setPopupContent(`
                <div class="bus-popup-content">
                    <div class="bus-popup-header">
                        <span>Parada ${i + 1} de ${schedule.stops.length}</span>
                    </div>
                    <h4 class="bus-popup-title">${schedule.stops[i]}</h4>
                    <div class="bus-popup-time">
                        <span>Salida ${trip[0]} · Paso estimado:</span>
                        <strong>${timeLabel}</strong>
                    </div>
                </div>
            `);
        });
    }
}

