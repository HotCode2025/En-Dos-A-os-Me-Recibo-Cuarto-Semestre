# Profundizando en los sistemas de numeración

# Sistema Decimal: Base 10
a = 10
print(f"a: {a} (Decimal)")

# Sistema Binario: Base 2
a = 0b1010
print(f"a: {a} (Binario)")

# Sistema Octal: Base 8
a = 0o12
print(f"a: {a} (Octal)")

# Sistema Hexadecimal: Base 16
a = 0xA
print(f"a: {a} (Hexadecimal)")


a = int('23', 10)  # Decimal
print(f"a base decimal: {a}")

a = int('10111', 2)  # Binario
print(f"a base binaria: {a}")

a = int('27', 8)  # Octal
print(f"a base octal: {a}")

a = int('17', 16)  # Hexadecimal
print(f"a base hexadecimal: {a}")

#Base 5 sus valores de 0 a 4
a = int('34', 5)
print(f"a base 5: {a}")
